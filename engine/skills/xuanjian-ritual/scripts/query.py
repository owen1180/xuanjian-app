def 模糊(数据, 键, 字段名):
    果 = []
    for x in 数据:
        for f in 字段名:
            v = x.get(f, "")
            if isinstance(v, list):
                v = "".join(v)
            if 键 in str(v):
                果.append(x)
                break
    return 果


