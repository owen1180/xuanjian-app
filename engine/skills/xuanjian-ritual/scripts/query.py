def 读(名):
    路径 = os.path.join(数据目录, 名 + ".json")
    with open(路径, encoding="utf-8") as f:
        return json.load(f)


def 条(文本, 宽=78):
    return 文本 if len(文本) <= 宽 else 文本[:宽 - 1] + "…"


