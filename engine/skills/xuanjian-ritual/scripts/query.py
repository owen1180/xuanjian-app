def selftest():
    """自检：数据自洽 + 「查不到就说查不到」两条底线。

    重点不在「函数能跑」，在**场景表和四张数据表对不对得上**。
    场景表是手写的，数据是抓来的，两边各改各的，必然出现「点进去是空的」——
    用户点「财」看见「招财符」，可 fulu 里没有这一条，等于凭空给了个名字。
    这种洞不报错、不崩，只是静默少一行，靠人眼看永远发现不了。
    """
    import io
    from contextlib import redirect_stdout
    通过, 失败 = [], []

    def 查(名, 条件):
        (通过 if 条件 else 失败).append(名)

    def 捕获(fn, *a):
        b = io.StringIO()
        with redirect_stdout(b):
            fn(*a)
        return b.getvalue()

    # ① 四张表读得出来
    科仪 = 读("keyi")["条目"]
    符 = 读("fulu")["条目"]
    功过 = 读("gongguo")
    查("数据·科仪非空", len(科仪) >= 10)
    查("数据·符咒非空", len(符) >= 10)
    查("数据·功格与过律都在", bool(功过.get("功格")) and bool(功过.get("过律")))
    查("数据·改运六层", len(读("gaifu")["层级"]) == 6)

    # ② 场景表里的每个名字，都必须在数据里真有一条（悬空引用＝凭空给名）
    科仪名 = {x["名"] for x in 科仪}
    符名 = {x["名"] for x in 符}
    门名 = {x["门"] for x in 功过["功格"]}
    悬空 = []
    for 键, 场 in 场景表.items():
        for 名 in 场.get("科仪", []):
            if 名 not in 科仪名:
                悬空.append("场景[%s]科仪→%s" % (键, 名))
        for 名 in 场.get("符", []):
            if 名 not in 符名:
                悬空.append("场景[%s]符→%s" % (键, 名))
    查("场景表·科仪符无悬空引用%s" % ("：" + "；".join(悬空[:3]) if 悬空 else ""), 悬空 == [])

    # ②b 功德引用要挂到功过格的「门」上，否则用户照着点了却找不到出处。
    #     现有两条是善行大类（不对应单一功格条目），单列成白名单；
    #     **一旦多出第三条就报**——那意味着有人加了不可核的引用，须人工定去留。
    未挂门 = set()
    for 键, 场 in 场景表.items():
        for 名 in 场.get("功德", []):
            if not any(门 in 名 for 门 in 门名):
                未挂门.add(名)
    查("场景表·功德引用都挂在已知门上（未挂门：%s）" % "／".join(sorted(未挂门)),
       未挂门 == {"孝亲与祭祖", "戒杀与护生"})

    # ③ 每个场景都要有说明与提示，不许只有一张名字表
    查("场景表·每场有说明", all(场.get("说明") for 场 in 场景表.values()))
    查("场景表·每场有提示", all(场.get("提示") for 场 in 场景表.values()))

    # ④ 查不到就说查不到（三条查无路径都不许现编）
    查("查无·科仪报未收录", "未收录" in 捕获(查科仪, "这个词一定没有"))
    查("查无·符报未收录", "未收录" in 捕获(查符, "这个词一定没有"))
    查("查无·典籍报未收录", "未收录" in 捕获(查典籍, "这本书一定没有"))
    查("查无·未知场景给可选表", "可选场景" in 捕获(查场景, "长生"))
    查("查无·非法档位给档位表", "甲／乙／丙／丁" in 捕获(查风险, "戊"))

    # ⑤ 丁档（一律拒绝）不许带做法：给了做法就等于教了
    丁 = [x for x in 科仪 if x["风险级"].startswith("丁")]
    查("丁档·确实存在", len(丁) >= 1)
    查("丁档·做法一律留空",
       all((x.get("常见做法") or "").strip() in ("", "—") for x in 丁))
    查("丁档·都写了不可承诺", all(x.get("不可承诺") for x in 丁))

    # ⑥ 模糊匹配能吃列表字段（别名存成 list，不处理就会永远匹配不上）
    查("模糊·命中文别名列表", 模糊(科仪, "礼斗", ["名", "别名"]))
    查("模糊·无关词不硬凑", 模糊(科仪, "量子力学", ["名", "别名", "目的"]) == [])

    # ⑦ 全览跑得通且报得出条数
    出 = 捕获(全览)
    查("全览·列出六层", "改运六层" in 出 and "科仪：" in 出)

    print("通过 %d ／ 失败 %d" % (len(通过), len(失败)))
    for x in 失败:
        print("  ✗", x)
    return 0 if not 失败 else 1


def 主程序():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    命令 = sys.argv[1]
    参数 = sys.argv[2] if len(sys.argv) > 2 else "全部"
    if 命令 == "--selftest":
        return selftest()
    if 命令 == "场景":
        查场景(参数)
    elif 命令 == "科仪":
        查科仪(参数)
    elif 命令 == "符":
        查符(参数)
    elif 命令 == "典籍":
        查典籍(参数)
    elif 命令 == "风险":
        查风险(参数)
    elif 命令 == "全览":
        全览()
    else:
        print(__doc__)


if __name__ == "__main__":
    sys.exit(主程序())

