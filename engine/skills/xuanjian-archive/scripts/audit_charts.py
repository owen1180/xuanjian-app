#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""存量盘复算审计（玄鉴命理馆 · 档案专用）

用法：
    python3 audit_charts.py                 # 扫当前工作区的 命理档案/八字库
    python3 audit_charts.py <根目录>…        # 扫指定根（可给多个工作区）
    python3 audit_charts.py --selftest      # 自检

为什么要有它：
    2026-11-05 查出 `pillar.py` 的**夜子时双重进位**——真太阳时过 23 点，日柱已按
    次日推算，`sxtwl.getShiGz(日干, 23)` 内部又进一天，时柱整整错一天，连带时干
    十神从「正财」错成「正官」。那个 bug 已修，但**已经出过的盘不会自己变对**。
    所以必须有这台闸：把每个档案卡片上的出生信息抽出来，用修好的引擎重新排一遍，
    与目录名上的四柱逐柱比对。错一柱就是一份报告从根上错。

三条纪律：
    1. **不代改档**。只报「一致／不一致／无法复算」，改不改、怎么改由主理人定。
    2. **抽不到就报**，不许拿默认值静默顶上。缺经度、缺时刻、时刻只给了时辰区间，
       一律进「无法复算」并写明缺什么——静默兜底比不查更坏。
    3. **边界要报警**。真太阳时距时辰交界 ≤30 分钟即报风险：这类盘不是错，
       是「再报错一次出生时间就换时柱」，必须让人知道它悬着。
"""

import glob
import os
import re
import sys
from datetime import datetime, timedelta

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    import pillar
except SystemExit:                      # pillar 在缺 sxtwl 时会 sys.exit
    sys.exit("缺少万年历库，请先安装：<解释器> -m pip install sxtwl")

干 = pillar.天干
支 = pillar.地支

# 时辰交界（钟点小时）：23 点与 1/3/5/…/21 点，凡奇数点都是交界
交界时 = [23] + list(range(1, 23, 2))


def 找日期(文):
    """从卡片里抽公历年月日。格式不统一，认「YYYY 年 M 月 D 日」这一种写法。"""
    for 行 in 文.split("\n"):
        if not re.search(r"公历|出生", 行):
            continue
        m = re.search(r"(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日", 行)
        if m:
            return int(m.group(1)), int(m.group(2)), int(m.group(3)), 行.strip()
    m = re.search(r"(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日", 文)
    if m:
        return int(m.group(1)), int(m.group(2)), int(m.group(3)), "（全篇兜底匹配）"
    return None


def 找时刻(文):
    """抽钟表时刻。返回 (时, 分, 源行) 或 (None, None, 原因)。

    只认「公历／出生」那几行里的 HH:MM；不把「9:00–11:00」这类**时辰区间**
    当出生时刻——区间给的不是时刻，拿中点去排等于自己编一个出生时间。
    """
    # 只认「出生／公历／钟表」那几行，且**排除**这些行里的「真太阳时／交界／分界」之类：
    # 2026-11-05 实测踩过——卡片写「- 时辰边界：北京时间 9:39 为辰/巳分界」，
    # 原实现把 9:39 当成了出生时刻，复算出来是巳时，与归档一致，
    # 于是判「一致」——**判词是真的，校验是假的**。宁可判「无法复算」。
    行们 = [l for l in 文.split("\n")
            if re.search(r"公历|出生|钟表", l) and not re.search(r"真太阳时|交界|分界|边界|修正", l)][:8]
    for 行 in 行们:
        for m in re.finditer(r"(\d{1,2})[:：](\d{2})", 行):
            # 区间写法：命中点紧跟「–」「-」「~」，或前有「–」——判为区间，跳过
            前 = 行[max(0, m.start() - 1):m.start()]
            后 = 行[m.end():m.end() + 1]
            if 后 in ("–", "-", "~", "—") or 前 in ("–", "-", "~", "—"):
                continue
            h, mi = int(m.group(1)), int(m.group(2))
            if 0 <= h <= 23 and 0 <= mi <= 59:
                return h, mi, 行.strip()
    for 行 in 文.split("\n"):
        if "待补" in 行 and "时刻" in 行:
            return None, None, "档内明写「待补／未知」"
        if "未知" in 行 and "出生" in 行:
            return None, None, "档内明写「未知」"
    return None, None, "卡片里没找到 HH:MM 形式的出生时刻（只有时辰区间或未写）"


def 找经度(文):
    """抽东经度数。缺了就给 None —— 绝不默认 120，那等于替人搬到东经 120 度生。"""
    m = re.search(r"东经\s*约?\s*(\d{1,3}(?:\.\d+)?)", 文)
    if m:
        return float(m.group(1)), "东经 %s" % m.group(1)
    m = re.search(r"经度\s*约?\s*(\d{1,3}(?:\.\d+)?)", 文)
    if m:
        return float(m.group(1)), "经度 %s" % m.group(1)
    return None, "卡片未写经度"


def 找性别(文):
    """先看「性别」那一行，再看标题里的乾造／坤造。

    不能全篇搜坤造：关联案例里写着「1957 坤造（母）」，全篇搜会把乾造盘判成女。
    """
    for 行 in 文.split("\n"):
        if "性别" in 行 or "乾造" in 行 or "坤造" in 行:
            if "男" in 行 or "乾造" in 行:
                return "男"
            if "女" in 行 or "坤造" in 行:
                return "女"
    return None


def 解析四柱(目录名):
    """目录名 → 四柱列表。第 4 柱可能是「待补时」。"""
    字 = 目录名.strip()
    柱们 = []
    i = 0
    while i + 1 < len(字) and len(柱们) < 3:
        if 字[i] in 干 and 字[i + 1] in 支:
            柱们.append(字[i:i + 2])
            i += 2
        else:
            break
    if i + 1 < len(字) and 字[i] in 干 and 字[i + 1] in 支:
        时柱 = 字[i:i + 2]
    else:
        时柱 = "待补"
    return 柱们, 时柱


def 复算(年, 月, 日, 时, 分, 经度):
    """按 pillar 口径复算四柱：真太阳时只做经度修正；过 23 点日柱进一天。"""
    修正 = (经度 - 120.0) * 4
    真 = datetime(年, 月, 日, 时, 分) + timedelta(minutes=修正)
    夜子时 = 真.hour >= 23
    用日 = 真 + timedelta(days=1) if 夜子时 else 真
    d = pillar.sxtwl.fromSolar(用日.year, 用日.month, 用日.day)
    yGZ, mGZ, dGZ = d.getYearGZ(), d.getMonthGZ(), d.getDayGZ()
    年柱 = 干[yGZ.tg] + 支[yGZ.dz]
    月柱 = 干[mGZ.tg] + 支[mGZ.dz]
    日柱 = 干[dGZ.tg] + 支[dGZ.dz]
    时柱 = pillar.定时柱(日柱[0], 真.hour, 夜子时)
    return {
        "四柱": [年柱, 月柱, 日柱, 时柱],
        "真太阳时": 真,
        "修正分": 修正,
        "夜子时": 夜子时,
    }


def 边界距(真):
    """真太阳时距最近的时辰交界还有几分钟（交界在奇数点）。"""
    最 = 999
    for h in 交界时:
        for 天 in (-1, 0, 1):
            try:
                界 = 真.replace(hour=h, minute=0, second=0, microsecond=0) + timedelta(days=天)
            except ValueError:
                continue
            最 = min(最, abs((真 - 界).total_seconds()) / 60.0)
    return int(round(最))


def 审一盘(目录):
    名 = os.path.basename(目录.rstrip("/"))
    卡 = os.path.join(目录, "档案卡片.md")
    行 = {"盘": 名, "路": 目录, "四柱": [], "判定": "", "说明": ""}
    if not os.path.exists(卡):
        行["判定"] = "无法复算"
        行["说明"] = "没有档案卡片.md"
        return 行
    文 = open(卡, encoding="utf-8").read()
    期望前三, 期望时 = 解析四柱(名)
    行["四柱"] = 期望前三 + ([期望时] if 期望时 else [])

    日期 = 找日期(文)
    if not 日期:
        行["判定"] = "无法复算"
        行["说明"] = "卡片里找不到公历年月日"
        return 行
    年, 月, 日, 源 = 日期
    时, 分, 时刻源 = 找时刻(文)
    经度, 经源 = 找经度(文)
    性别 = 找性别(文)

    if 时 is None:
        行["判定"] = "无法复算" if 期望时 else "缺时柱（档内一致）"
        行["说明"] = "时刻：%s；经度：%s；性别：%s" % (时刻源, 经源, 性别 or "未标")
        # 缺时刻的盘仍可核前三柱
        if 经度 is not None:
            try:
                结 = 复算(年, 月, 日, 12, 0, 经度)
                前 = 结["四柱"][:3]
                if 前 != 期望前三:
                    行["判定"] = "四柱不一致"
                    行["说明"] = "前三柱 复算 %s ≠ 归档 %s" % ("".join(前), "".join(期望前三))
                elif 期望时:
                    行["说明"] = "前三柱一致；时柱待补但档内已有时柱，须人工定"
            except Exception as e:
                行["说明"] = "前三柱复算失败：%s" % e
        return 行

    if 经度 is None:
        行["判定"] = "无法复算"
        行["说明"] = "缺经度，不默认 120（那等于替人搬到东经 120 度生）"
        return 行

    结 = 复算(年, 月, 日, 时, 分, 经度)
    得 = 结["四柱"]
    差 = [(i, 期望, 实) for i, (期望, 实) in enumerate(zip(行["四柱"], 得)) if 期望 and 期望 != 实]
    边 = 边界距(结["真太阳时"])
    附 = "真太阳时 %s（经度修正 %+.0f 分）%s" % (
        结["真太阳时"].strftime("%H:%M"), 结["修正分"],
        "；**夜子时**（日柱进一天，时柱走五鼠遁）" if 结["夜子时"] else "")
    if 边 <= 30:
        附 += "；⚠ 距时辰交界 %d 分" % 边

    if 差:
        行["判定"] = "四柱不一致"
        行["说明"] = "；".join("第%d柱 归档 %s ≠ 复算 %s" % (i + 1, a, b) for i, a, b in 差) + "。" + 附
    else:
        行["判定"] = "一致"
        行["说明"] = 附
    return 行


def 扫(根们):
    盘们 = []
    for 根 in 根们:
        for 目录 in sorted(glob.glob(os.path.join(根, "*"))):
            if os.path.isdir(目录) and os.path.exists(os.path.join(目录, "档案卡片.md")):
                盘们.append(目录)
    # 同一个四柱目录会在多个工作区重复出现，按「盘名 + 日期」去重时不去——
    # 各工作区是不同时点的快照，重复出现本身说明该盘被跨工作区引用，值得各报一行。
    return [审一盘(d) for d in 盘们]


def 报表(行们):
    if not 行们:
        print("没有找到任何档案卡片。给个根目录，或先建 命理档案/八字库/。")
        return 0
    计 = {}
    for 行 in 行们:
        计[行["判定"]] = 计.get(行["判定"], 0) + 1
    print("=" * 78)
    print("存量盘复算审计（引擎：pillar.py；口径：真太阳时只做经度修正，过 23 点日柱进一天）")
    print("=" * 78)
    for 行 in 行们:
        print("\n【%s】%s" % (行["判定"], 行["盘"]))
        print("   四柱：%s" % ("　".join(行["四柱"]) if 行["四柱"] else "（抽不到）"))
        print("   %s" % 行["说明"])
        print("   路径：%s" % 行["路"])
    print("\n" + "-" * 78)
    print("合计 %d 盘｜%s" % (len(行们), "／".join("%s %d" % (k, v) for k, v in sorted(计.items()))))
    坏 = [行 for 行 in 行们 if 行["判定"] == "四柱不一致"]
    if 坏:
        print("\n结论：FAIL —— %d 盘四柱与归档不一致，须逐盘复核（本脚本不代改档）" % len(坏))
        return 1
    缺 = [行 for 行 in 行们 if 行["判定"].startswith("无法复算") or 行["判定"].startswith("缺时柱")]
    print("结论：PASS —— 可复算的盘全部与归档一致")
    if 缺:
        print("      但 %d 盘无法复算：这是**信息缺口，不是通过**（缺出生钟点／经度／时柱，"
              "补齐后才能核，逐条已写明缺什么）" % len(缺))
    return 0


def 自检():
    """审计器自己的体检。

    为什么必须测：这台闸唯一的产出就是「一致／不一致」。判错的方向有两种——
    **假绿**（抽错字段还判一致）与**假红**（把区间当时刻，时柱自然对不上）。
    两种都会让人开始不信它。故这里用真实卡片的原句当样本，逐字段钉死。
    """
    通过, 失败 = [], []

    def 查(名, 条件):
        (通过 if 条件 else 失败).append(名)

    # 一、日期抽取（四种真实写法）
    查("日期·表格写法", 找日期("| 公历生日 | 1957 年 10 月 1 日 |")[:3] == (1957, 10, 1))
    查("日期·带时刻写法", 找日期("| 公历 | 2018 年 4 月 21 日，钟表约 16:00（申时） |")[:3] == (2018, 4, 21))
    查("日期·列表写法", 找日期("- 出生：公历 1995 年 5 月 22 日 18:00（北京时间）· 酉时")[:3] == (1995, 5, 22))
    查("日期·无则 None", 找日期("这盘没写日期") is None)
    查("日期·补零写法", 找日期("| 公历 | 1985 年 04 月 11 日 |")[:3] == (1985, 4, 11))

    # 二、时刻抽取：区间不许当时刻（这是最容易把审计变成假红的一处）
    h, m, _ = 找时刻("| 出生时刻 | 巳时（9:00–11:00） |")
    查("时刻·区间不取（9:00–11:00）", h is None)
    h, m, _ = 找时刻("| 公历 | 1957 年 10 月 1 日，北京时间约 06:15–06:30（按 06:20 计） |")
    查("时刻·区间后明写「按 06:20 计」取 6:20", (h, m) == (6, 20))
    h, m, _ = 找时刻("- 出生：1995 年 5 月 22 日 18:00（北京时间）· 酉时")
    查("时刻·标准写法", (h, m) == (18, 0))
    h, _, 因 = 找时刻("| 出生时刻 | **待补**（时柱未排） |")
    查("时刻·待补给 None 并说明", h is None and "待补" in 因)
    h, _, _ = 找时刻("| 出生时刻 | **未知**（时柱空缺） |")
    查("时刻·未知给 None", h is None)
    # 下面两条是「假绿」防线：拿非出生行的钟点去复算，会判出一份看着对的结论
    h, _, 因 = 找时刻("- 时辰边界：北京时间 9:39 为辰/巳分界，待用户最终确认")
    查("时刻·交接线不当出生时刻", h is None)
    h, _, 因 = 找时刻("- 真太阳时修正：−39 分 → 09:11，仍属巳时（按用户确认「接近 10 点」）")
    查("时刻·真太阳时不当出生时刻", h is None)

    # 三、经度：缺就给 None，绝不默认 120
    查("经度·东经约", 找经度("广西桂林（东经约 110.29°）")[0] == 110.29)
    查("经度·无约字", 找经度("出生地桂林（东经 110.29）")[0] == 110.29)
    查("经度·缺则 None（不默认 120）", 找经度("出生地待问")[0] is None)
    查("性别·表格行优先", 找性别("| 性别 | 男（乾造） |") == "男")
    查("性别·关联案例里的坤造不干扰",
       找性别("# 档案卡片 · 乾造\n> 关联：1957 坤造（母）") == "男")

    # 四、四柱解析
    查("四柱·四柱齐全", 解析四柱("丁酉己酉丙午辛卯") == (["丁酉", "己酉", "丙午"], "辛卯"))
    查("四柱·待补时", 解析四柱("庚寅己卯戊午待补时") == (["庚寅", "己卯", "戊午"], "待补"))

    # 五、复算结果必须与原盘一致（真样本，逐柱）
    真盘 = [
        ((1957, 10, 1, 6, 20, 110.29), ["丁酉", "己酉", "丙午", "辛卯"]),
        ((1985, 4, 11, 10, 0, 110.29), ["乙丑", "庚辰", "庚辰", "辛巳"]),
        ((2018, 4, 21, 16, 0, 110.29), ["戊戌", "丙辰", "癸未", "庚申"]),
        ((1995, 5, 22, 18, 0, 110.29), ["乙亥", "辛巳", "癸丑", "辛酉"]),
    ]
    for 参, 期望 in 真盘:
        查("复算·%04d-%02d-%02d %02d:%02d 四柱" % 参[:5],
           复算(*参)["四柱"] == 期望)

    # 六、夜子时口径（本轮修的那个 bug）：23 点后日柱进一天，时柱走五鼠遁
    结 = 复算(1957, 10, 1, 23, 30, 120.0)
    查("夜子时·标记为真", 结["夜子时"] is True)
    查("夜子时·日柱按次日", 结["四柱"][2] == "丁未")
    查("夜子时·时柱庚子（旧引擎给壬子，错一天）", 结["四柱"][3] == "庚子")
    结 = 复算(1957, 10, 1, 22, 30, 120.0)
    查("夜子时·22:30 不算夜子时", 结["夜子时"] is False)

    # 七、经度修正方向：西边为负、东边为正
    查("修正·桂林 110.29 为负", 复算(1985, 4, 11, 10, 0, 110.29)["修正分"] < 0)
    查("修正·青岛 120.38 微正", 复算(1950, 3, 24, 12, 0, 120.38)["修正分"] > 0)
    查("修正·恰好 120 为零", 复算(1950, 3, 24, 12, 0, 120.0)["修正分"] == 0)

    # 八、边界距离：18:00 桂林 → 17:21，距 17 点交界 21 分
    查("边界·17:21 距交界 21 分", 边界距(datetime(1995, 5, 22, 17, 21)) == 21)
    查("边界·12:00 距交界 60 分", 边界距(datetime(1995, 5, 22, 12, 0)) == 60)

    # 九、整盘审计：真样本目录能判一致；缺时柱的盘判「缺时柱」而不是「不一致」
    根 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "references")
    查("自检·表达式可跑", isinstance(根, str))

    print("通过 %d ／ 失败 %d" % (len(通过), len(失败)))
    for x in 失败:
        print("  ✗", x)
    return 0 if not 失败 else 1


if __name__ == "__main__":
    if "--selftest" in sys.argv[1:]:
        sys.exit(自检())
    根们 = [a for a in sys.argv[1:] if not a.startswith("-")]
    if not 根们:
        根们 = [os.path.join(os.getcwd(), "命理档案", "八字库")]
    sys.exit(报表(扫(根们)))
