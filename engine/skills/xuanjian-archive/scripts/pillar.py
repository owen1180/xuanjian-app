def 十神(日干, 他干):
    """按五行生克关系定十神简称"""
    日五行属 = 五行归属(日干)
    他五行属 = 五行归属(他干)
    同异 = "同" if 五行阴阳(日干) == 五行阴阳(他干) else "异"
    关系 = 五行关系(日五行属, 他五行属)
    键值 = (关系, 同异)
    表 = {
        ("同我", "同"): "比肩", ("同我", "异"): "劫财",
        ("我生", "同"): "食神", ("我生", "异"): "伤官",
        ("我克", "同"): "偏财", ("我克", "异"): "正财",
        ("克我", "同"): "七杀", ("克我", "异"): "正官",
        ("生我", "同"): "偏印", ("生我", "异"): "正印",
    }
    return 表[键值]


def 五行归属(干):
    for 行, 字 in 五行.items():
        if 干 in 字:
            return 行
    return "土"


def 五行阴阳(干):
    return 天干.index(干) % 2


def 五行关系(我方, 他方):
    生 = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
    克 = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}
    if 我方 == 他方:
        return "同我"
    if 生[我方] == 他方:
        return "我生"
    if 克[我方] == 他方:
        return "我克"
    if 克[他方] == 我方:
        return "克我"
    return "生我"


def 五鼠遁(日干, 时支):
    起 = {"甲": 0, "己": 0, "乙": 2, "庚": 2, "丙": 4, "辛": 4, "丁": 6, "壬": 6, "戊": 8, "癸": 8}
    idx = 起[日干] + 地支.index(时支)
    return 天干[idx % 10]


def 时辰支(小时):
    """23–1 点为子时，依此类推"""
    return 地支[((int(小时) + 1) // 2) % 12]


def 定时柱(日干, 小时, 夜子时=False):
    """定日时柱：返回「干+支」两字。

    夜子时（真太阳时 >= 23 点）必须走五鼠遁，不能问库。原因（2026-11-05 实测）：
    本脚本口径是「过了 23 点，日柱按次日推算」，日干**已经**进了一天；
    而 sxtwl.getShiGz(日干, 23) 内部还会再进一天，于是双重进位——
    1957-10-01 23:30 的盘，日柱丁未，正确时柱庚子，库给出壬子（戊日子时），
    整整错一天，且连带时干十神从「正财」错成「正官」。
    原来只在两算法不一致时 print 一行警示，进程照样退 0，四柱照出。
    """
    时支字 = 时辰支(小时)
    if 夜子时:
        return 五鼠遁(日干, 时支字) + 时支字
    gz = sxtwl.getShiGz(天干.index(日干), 小时)
    if gz.dz != 地支.index(时支字):      # 库的时支与本地口径不符时，以本地口径为准
        return 五鼠遁(日干, 时支字) + 时支字
    return 天干[gz.tg] + 地支[gz.dz]


def 找最近节(基准时刻, 顺排):
    """返回最近一个「节」的名称与精确时刻；节气索引自冬至起，奇数为节"""
    步长 = 1 if 顺排 else -1
    for 偏移 in range(1, 40):
        候选 = 基准时刻 + datetime.timedelta(days=偏移 * 步长)
        d = sxtwl.fromSolar(候选.year, 候选.month, 候选.day)
        if d.hasJieQi():
            索引 = d.getJieQi()
            if 索引 % 2 != 1:      # 是「气」不是「节」，跳过
                continue
            t = sxtwl.JD2DD(d.getJieQiJD())
            return 节气名[索引], datetime.datetime(int(t.Y), int(t.M), int(t.D), int(t.h), int(t.m))
    return None, None


def 主程序():
    p = argparse.ArgumentParser(description="四柱排盘与核盘")
    p.add_argument("year", type=int, help="公历年")
    p.add_argument("month", type=int, help="公历月")
    p.add_argument("day", type=int, help="公历日")
    p.add_argument("--hour", type=int, help="出生钟表时刻（24 小时制）")
    p.add_argument("--minute", type=int, default=0, help="出生分钟")
    p.add_argument("--lon", type=float, default=120.0, help="出生地经度，东经为正，默认 120 不修正")
    p.add_argument("--sex", choices=["男", "女"], default="男", help="性别，定大运顺逆")
    a = p.parse_args()

    print("=" * 52)
    print("核盘：公元 %d 年 %d 月 %d 日" % (a.year, a.month, a.day))

    # 一、真太阳时修正
    修正分钟 = (a.lon - 120.0) * 4
    出生时刻 = datetime.datetime(a.year, a.month, a.day, a.hour or 12, a.minute)
    用时 = 出生时刻
    if a.hour is not None:
        用时 = 出生时刻 + datetime.timedelta(minutes=修正分钟)
        print("出生钟表时刻：%02d:%02d 　经度 %.2f 度 → 修正 %+.0f 分 → 真太阳时 %02d:%02d"
              % (a.hour, a.minute, a.lon, 修正分钟, 用时.hour, 用时.minute))
    else:
        print("未给出出生时刻 → 时柱待补，其余三柱与大运不受影响")

    # 二、夜子时处理（真太阳时跨到 23 点后，日柱进一位）
    用日 = 用时
    夜子时 = 用时.hour >= 23
    if 夜子时:
        用日 = 用时 + datetime.timedelta(days=1)
        print("注意：真太阳时已过夜子时，日柱按次日推算（另一派用当日，可自行取舍）")

    d = sxtwl.fromSolar(用日.year, 用日.month, 用日.day)
    农年 = d.getLunarYear()
    闰月 = "闰" if d.isLunarLeap() else ""
    print("农历：%d 年 %s%d 月 %d 日" % (农年, 闰月, d.getLunarMonth(), d.getLunarDay()))

    yGZ, mGZ, dGZ = d.getYearGZ(), d.getMonthGZ(), d.getDayGZ()
    年柱 = 天干[yGZ.tg] + 地支[yGZ.dz]
    月柱 = 天干[mGZ.tg] + 地支[mGZ.dz]
    日柱 = 天干[dGZ.tg] + 地支[dGZ.dz]

    if a.hour is None:
        时柱 = "待补"
        时支 = None
    else:
        时柱 = 定时柱(日柱[0], 用时.hour, 夜子时)
        时支 = 时柱[1]
        # 五鼠遁手算交叉校验
        手算 = 五鼠遁(日柱[0], 时辰支(用时.hour))
        if 手算 != 时柱[0] or 时辰支(用时.hour) != 时支:
            print("警示：时柱两算法不一致（库=%s，五鼠遁=%s），请人工判定" % (时柱, 手算 + 时辰支(用时.hour)))
        print("时辰：%s（%s 时 %02d:%02d）" % (时支, "夜子" if 夜子时 else "常", 用时.hour, 用时.minute))

    print("-" * 52)
    print("四柱：%s　%s　%s　%s" % (年柱, 月柱, 日柱, 时柱))
    print("日主：%s（%s）" % (日柱[0], 五行归属(日柱[0])))

    # 三、十神
    四柱干 = [年柱[0], 月柱[0], 日柱[0]] + ([时柱[0]] if 时柱 != "待补" else [])
    十神排 = [十神(日柱[0], g) for g in 四柱干]
    print("天干十神：年%s 月%s 时%s" % (十神排[0], 十神排[1], 十神排[3] if 时柱 != "待补" else "待补"))
    if 时支:
        print("时支藏干本气：%s（%s）" % (本气[时支], 十神(日柱[0], 本气[时支])))

    # 四、五行个数
    统计 = {"木": 0, "火": 0, "土": 0, "金": 0, "水": 0}
    for 字 in (年柱 + 月柱 + 日柱 + (时柱 if 时柱 != "待补" else "")):
        for 行, 群 in 五行.items():
            if 字 in 群:
                统计[行] += 1
    print("五行个数：木%d 火%d 土%d 金%d 水%d" % (统计["木"], 统计["火"], 统计["土"], 统计["金"], 统计["水"]))
    缺 = [行 for 行, n in 统计.items() if n == 0]
    if 缺:
        print("缺失：%s → 相应六亲与调候须留意" % "、".join(缺))

    # 五、大运顺逆与起运
    阳年 = (yGZ.tg % 2) == 0
    顺排 = 阳年 if a.sex == "男" else (not 阳年)
    print("-" * 52)
    print("年干：%s（%s年）　性别：%s　→ 大运%s排" % (年柱[0], "阳" if 阳年 else "阴", a.sex, "顺" if 顺排 else "逆"))

    名, 交节 = 找最近节(用时, 顺排)
    if 名 and 交节:
        差天 = abs((交节 - 用时).total_seconds()) / 86400.0
        岁 = int(差天 // 3)
        余天 = 差天 - 岁 * 3
        月 = int(余天 * 4)
        print("最近之节：%s（%s）" % (名, 交节.strftime("%Y-%m-%d %H:%M")))
        print("出生至交节：%.2f 日 → 三日为一岁 → 约 %d 岁 %d 个月起运" % (差天, 岁, 月))
        if a.hour is None:
            print("提示：未给出生时刻，起运折算以当日 12:00 为基准，误差在一个月内")
    else:
        print("未取得最近交节，请检查日期")

    print("=" * 52)


