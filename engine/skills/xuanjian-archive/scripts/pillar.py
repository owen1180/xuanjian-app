def 自检():
    """排盘引擎自己的体检。

    为什么必须测：本脚本是全馆**唯一**的确定性排盘源，`score.py` 判强弱、
    `yun.py` 判岁运，用的都是这里出的四柱。它错一位，后面全错，而且错得
    很像对的——分数、档位、断语都照常输出，没有一处会报错。

    另有一件事只有这里能测：脚本运行时若「库算时柱」与「五鼠遁手算」不一致，
    只会 print 一行警示，**进程照样退 0**。本节把它变成 120 组全量断言，
    从「打印一句」升级成「可回归」。
    """
    通过, 失败 = [], []

    def 查(名, 条件):
        (通过 if 条件 else 失败).append(名)

