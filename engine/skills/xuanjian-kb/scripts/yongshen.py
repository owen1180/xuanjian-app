# 5. 用神层次与力度（39 册）
# ---------------------------------------------------------------------------
def 判层次(扶抑, 调候, 通关):
    """按 39 §1 三项功能权重（扶抑6/调候3/通关1）判四等层次。"""
    分 = 0
    有 = []
    if 扶抑["用神五行列表"]:
        分 += 6
        有.append("扶抑")
    调候与扶抑合 = (调候["调候五行"] in 扶抑["用神五行列表"]) if 扶抑["用神五行列表"] else False
    if 调候与扶抑合:
        分 += 3
        有.append("调候(与扶抑合)")
    elif 调候["调候五行"]:
        有.append("调候(单列，不加分)")
    if 通关.get("兼任通关"):
        分 += 1
        有.append("通关(兼任)")

    # 39 §2 四等层次，按功能分反推（扶抑6 / 调候3 / 通关1）：
    #   10 = 扶抑+调候+通关 → 高等
    #    7 = 扶抑+通关，9 = 扶抑+调候 → 中等
    #    6 = 只有扶抑 → 中低
