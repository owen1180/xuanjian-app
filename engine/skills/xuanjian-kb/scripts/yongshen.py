def 判力度(四柱, 用神五行列表):
    """判用神虚透/实透——39 §3「用神虚透只能断到温饱」。"""
    if not 用神五行列表:
        return {"力度": "未定", "说明": "用神未定，不作力度判断"}
    实透 = []
    虚透 = []
    for 位, 柱 in zip(["年", "月", "日", "时"], 四柱):
        gan, zhi = 柱[0], 柱[1]
        for w in 用神五行列表:
            # 天干有字
            if 五行[gan] == w:
                # 地支有无本气根（根在看是否同五行藏于支）
                有根 = any(五行[hg] == w for hg in 藏干[zhi])
                (实透 if 有根 else 虚透).append(f"{位}干{gan}")
            # 地支本气
            if 支五行[zhi] == w:
                实透.append(f"{位}支{zhi}")
    if 实透:
        return {"力度": "实透", "位置": 实透 + 虚透,
                "说明": "用神有根，力量可用；可断实质吉凶"}
    if 虚透:
        return {"力度": "虚透", "位置": 虚透,
                "说明": "用神无根，是空头承诺；只能断温饱安稳，断不了大发"}
    return {"力度": "缺席", "位置": [],
            "说明": "原局用神不现，须靠大运补；本命层次按缺席论，不作高断"}


