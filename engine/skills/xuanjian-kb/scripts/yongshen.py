    if len(四柱) != 4 or any(len(c) != 2 for c in 四柱):
        raise ValueError("四柱须为四个两字干支，如 甲子 丙寅 戊辰 庚申")

    # 复用 score.py 定档——不重复实现打分，避免两处口径漂移
    档位 = "未定"
    分数 = None
    try:
        import score
        r = score.打分(四柱)
        档位 = r["档位"]
        分数 = r["总分"]
    except Exception:
        pass

    神表 = 十神全表(四柱)
    计数 = 十神统计(神表)
    调候判 = 判调候(四柱)
    扶抑判 = 判扶抑(四柱, 档位, 计数)
