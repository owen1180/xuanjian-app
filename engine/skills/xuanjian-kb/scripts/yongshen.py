def 判通关(四柱, 十神计数: dict, 扶抑判: dict):
    """判定扶抑用神**是否兼任通关**。

    这里不另提一个通关五行——`47` §4 明写「取用路线不能并用」，
    若通关另取一五行，就会和扶抑打架（实测曾出现「扶抑取水、通关取火」的自相矛盾）。
    所以通关只做一件事：**检查已经定下的扶抑用神，是否正好处在两强之间**。
    是则加 1 分（`39` §1 通关权重 1 分），否则不加。
    """
    if not 扶抑判["用神五行列表"]:
        return {"兼任通关": False, "通关五行": None,
                "说明": "用神未定，不判通关", "依据": "02 §2"}

    日干 = 四柱[2][0]
    日五行 = 五行[日干]
    用神 = set(扶抑判["用神五行列表"])

    官杀数 = 十神计数.get("正官", 0) + 十神计数.get("七杀", 0)
    比劫数 = 十神计数.get("比肩", 0) + 十神计数.get("劫财", 0)
    印数 = 十神计数.get("正印", 0) + 十神计数.get("偏印", 0)
    财数 = 十神计数.get("正财", 0) + 十神计数.get("偏财", 0)

    印五行 = 被生[日五行]

    # 典型一：官杀 与 比劫 两强相战 → 通关物是印（化官杀以生身）
    if 官杀数 >= 2 and 比劫数 >= 2:
        if 印五行 in 用神:
            return {"兼任通关": True, "通关五行": 印五行,
                    "说明": f"官杀与比劫两强相战，用神{印五行}（印）正兼通关——化官杀以生身",
                    "依据": "02 §2「通关用神：两强相战，取中间通关之物」+ 39 §1 通关 1 分"}
        return {"兼任通关": False, "通关五行": 印五行,
                "说明": f"官杀与比劫两强相战，本可取{印五行}（印）通关，但与扶抑用神不同路——"
                        f"按「路线不能并用」，只作背景说明，不加分",
                "依据": "47 §4「取用路线不能并用」"}

    # 典型二：财 与 印 两强相战 → 通关物是官杀（财生官、官生印）
    if 财数 >= 2 and 印数 >= 2:
        官五行 = 被克[日五行]
        if 官五行 in 用神:
            return {"兼任通关": True, "通关五行": 官五行,
                    "说明": f"财与印两强相战，用神{官五行}（官杀）正兼通关——财生官、官生印",
                    "依据": "39 §5「喜印而财能生官，官能生印」走成流通"}
        return {"兼任通关": False, "通关五行": 官五行,
                "说明": f"财与印两强相战，本可取{官五行}（官杀）通关，但与扶抑用神不同路——不加分",
                "依据": "47 §4「取用路线不能并用」"}

    return {"兼任通关": False, "通关五行": None,
            "说明": "无显著两强相战，不以通关加分",
            "依据": "02 §2"}


