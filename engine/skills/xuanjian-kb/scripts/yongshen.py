def 判扶抑(四柱, 档位: str, 十神计数: dict):
    """按强弱档位与十神结构取扶抑用神。

    返回 {"用神五行列表": [...], "忌神五行列表": [...], "路线": str, "依据": str}

    **取用只有一条路线，不许并列**（`47` §4「取用路线不能并用」）。
    下面每个分支都返回**单一方向**的五行列表，多五行只表示「同路线的
    印比/食伤财官同类」，不是两条路线并用。
    """
    日干 = 四柱[2][0]
    日五行 = 五行[日干]
    印五行 = 被生[日五行]     # 生我者
    比劫五行 = 日五行
    食伤五行 = 生[日五行]      # 我生者
    财五行 = 克[日五行]        # 我克者
    官杀五行 = 被克[日五行]    # 克我者

    印数 = 十神计数.get("正印", 0) + 十神计数.get("偏印", 0)
    比劫数 = 十神计数.get("比肩", 0) + 十神计数.get("劫财", 0)
    食伤数 = 十神计数.get("食神", 0) + 十神计数.get("伤官", 0)
    财数 = 十神计数.get("正财", 0) + 十神计数.get("偏财", 0)
    官杀数 = 十神计数.get("正官", 0) + 十神计数.get("七杀", 0)

    if 档位 == "偏旺":
        # 02 §1.1：顺序即优先级，命中即返回，不并列
        if 印数 >= 2 and 印数 >= 比劫数:
            return {"用神五行列表": [财五行], "忌神五行列表": [印五行, 比劫五行],
                    "路线": "印多导致偏旺 → 取财破印",
                    "依据": "02 §1.1「印多导致 → 财，财能克印，先制印这个病」"}
        if 食伤数 >= 1 and 官杀数 >= 2:
            return {"用神五行列表": [食伤五行], "忌神五行列表": [比劫五行, 印五行],
                    "路线": "食伤与官杀混杂 → 取食伤制杀",
                    "依据": "02 §1.1「身强、官杀亦强 → 食神制杀，制比化官更优」"}
        if 官杀数 >= 2 and 官杀数 > 食伤数:
            return {"用神五行列表": [食伤五行], "忌神五行列表": [比劫五行, 印五行],
                    "路线": "身强官杀亦强 → 食神制杀",
                    "依据": "02 §1.1「身强、官杀亦强 → 食神制杀」"}
        if 财数 == 0 and 食伤数 >= 1:
            return {"用神五行列表": [财五行], "忌神五行列表": [比劫五行, 印五行],
                    "路线": "身强无财只有食伤 → 取财",
                    "依据": "02 §1.1「身强无财、只有食伤 → 财，食伤要落到财上才有用」"}
        if 财数 >= 2:
            return {"用神五行列表": [官杀五行], "忌神五行列表": [比劫五行],
                    "路线": "身强财亦强 → 取官护财",
                    "依据": "02 §1.1「身强、财亦强 → 官，财旺需官护」"}
        return {"用神五行列表": [官杀五行], "忌神五行列表": [比劫五行, 印五行],
                "路线": "比劫导致偏旺 → 取官杀",
                "依据": "02 §1.1「比劫导致 → 官杀」"}

    if 档位 == "太旺":
        if 印数 >= 2 and 印数 > 食伤数:
            return {"用神五行列表": [比劫五行], "忌神五行列表": [印五行],
                    "路线": "印多导致太旺 → 取比劫化印（顺势）",
                    "依据": "02 §1.2「印多的太旺 → 比劫，用比劫化印，仍是顺势」"}
        return {"用神五行列表": [食伤五行], "忌神五行列表": [官杀五行, 印五行],
                "路线": "比劫导致太旺 → 取食伤顺势化泄",
                "依据": "02 §1.2「比劫导致的太旺 → 食伤为第一用神，顺势化泄」"}

    if 档位 == "专旺":
        主 = 印五行 if 印数 > 比劫数 else 比劫五行
        return {"用神五行列表": [主], "忌神五行列表": [官杀五行, 财五行, 食伤五行],
                "路线": "专旺 → 顺其气势，取生扶最强者",
                "依据": "02 §1.3「满盘生扶，以生扶为第一用神；专旺最忌逆势」"}

    if 档位 == "中和":
        return {"用神五行列表": [], "忌神五行列表": [],
                "路线": "中和 → 动态取用：生扶之运用泄耗，泄耗之运用生扶",
                "依据": "02 §1.4「中和最难取用，实操区间 100–120 分；不许铁口」"}

    if 档位 == "偏弱":
        if 印数 >= 2 and 比劫数 == 0:
            return {"用神五行列表": [比劫五行], "忌神五行列表": [财五行, 官杀五行],
                    "路线": "身弱印旺 → 先取比劫，不取印",
                    "依据": "score.py 释义「身弱而印旺者先取比劫，不取印」"}
        return {"用神五行列表": [印五行, 比劫五行], "忌神五行列表": [财五行, 官杀五行, 食伤五行],
                "路线": "偏弱 → 生扶，取印比",
                "依据": "02 §1.5「偏弱：生扶为主，取印比」"}

    if 档位 == "太弱":
        return {"用神五行列表": [食伤五行, 财五行, 官杀五行],
                "忌神五行列表": [印五行, 比劫五行],
                "路线": "太弱 → 顺势化泄，从其所旺；怕生扶",
                "依据": "02 §1.6「从弱者顺势，不可扶。扶之则反噬」"}

    return {"用神五行列表": [], "忌神五行列表": [], "路线": "档位未识别",
            "依据": "须先跑 score.py 定档"}


