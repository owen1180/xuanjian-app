def 取十神(日干: str, 他干: str) -> str:
    """定一个天干对日干的十神名。"""
    我, 他 = 五行[日干], 五行[他干]
    同阴 = 阴阳[日干] == 阴阳[他干]
    if 我 == 他:
        return 十神表[("同", 同阴)]
    if 生[我] == 他:
        return 十神表[("生", 同阴)]
    if 克[我] == 他:
        return 十神表[("克", 同阴)]
    if 克[他] == 我:
        return 十神表[("被克", 同阴)]
    if 生[他] == 我:
        return 十神表[("被生", 同阴)]
    raise ValueError(f"无法定十神：{日干} vs {他干}")


def 十神全表(四柱):
    """逐干逐藏干定十神。返回 dict。"""
    日干 = 四柱[2][0]
    位名 = ["年", "月", "日", "时"]
    天干十神 = {}
    地支十神 = {}
    for i, 柱 in enumerate(四柱):
        gan, zhi = 柱[0], 柱[1]
        名 = 取十神(日干, gan)
        天干十神[位名[i]] = {"干": gan, "十神": 名,
                            "阴阳": 阴阳[gan], "五行": 五行[gan]}
        # 日干本身不算「相对于自己」的十神，标为日主
        if i == 2:
            天干十神["日"]["十神"] = "日主"
        支下 = []
        for hg in 藏干[zhi]:
            支下.append({"藏干": hg, "十神": 取十神(日干, hg),
                        "五行": 五行[hg]})
        地支十神[位名[i]] = {"支": zhi, "藏干": 支下}
    return {"天干": 天干十神, "地支": 地支十神}


def 十神统计(表):
    """统计十神出现次数（天干各一，地支按藏干计）。"""
    计 = {}
    for v in 表["天干"].values():
        if v["十神"] == "日主":
            continue
        计[v["十神"]] = 计.get(v["十神"], 0) + 1
    for v in 表["地支"].values():
        for hg in v["藏干"]:
            计[hg["十神"]] = 计.get(hg["十神"], 0) + 1
    return 计


