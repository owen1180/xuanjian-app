# 天干基准分：先看特例，再按柱型
天干特例 = {
    ("甲", "辰"): 36, ("甲", "戌"): 25,
    ("壬", "辰"): 22, ("癸", "丑"): 22,
    ("丁", "未"): 36,
}
柱型基准 = {"通根": 54, "支生干": 47, "干生支": 25, "盖头": 25, "截脚": 18}
支生干_四十三 = {"甲子", "丁卯", "庚辰", "辛未", "癸酉"}

# 地支本气分的特例
地支特例 = {
    ("甲辰", "戊"): 18, ("甲戌", "戊"): 30,
    ("壬辰", "戊"): 42, ("癸丑", "己"): 42,
    ("丁未", "己"): 78,
}

强弱档 = [(45, "太弱"), (105, "偏弱"), (115, "中和"), (272, "偏旺"), (435, "太旺")]


def 柱型(gan, zhi):
    """判定一柱的干支关系。"""
    gw, zw = 五行[gan], 支五行[zhi]
    if gw == zw:
        return "通根"
    if 生[zw] == gw:
        return "支生干"
    if 生[gw] == zw:
        return "干生支"
    if 克[gw] == zw:
        return "盖头"
    if 克[zw] == gw:
        return "截脚"
    return "无关"


def 天干增减(日干, 他干):
    """他干对日干的作用百分比（正为增力，负为减力）。"""
    a, b = 五行[日干], 五行[他干]
    同性 = 阴阳[日干] == 阴阳[他干]
    if a == b:
        return 20 if 同性 else 30
    if 生[b] == a:          # 他干生我，我为被生方
        return 20 if 同性 else 30
    if 生[a] == b:          # 我生他干，我为主生方
        return -20 if 同性 else -30
    if 克[a] == b:          # 我克他干，我为主克方
        return -30 if 同性 else -15
    if 克[b] == a:          # 他干克我，我为被克方
        return -50 if 同性 else -30
    return 0


def 本气分(柱, 本气干, 原值, 型, 得令):
    """地支本气在柱型作用后的分数。"""
    if (柱, 本气干) in 地支特例:
        return float(地支特例[(柱, 本气干)])
    if 型 == "通根":
        return float(原值)
    if 型 == "干生支":
        return 原值 * 1.3
    if 型 == "支生干":
        if 原值 >= 100:
            return 80.0
        if 柱[1] in ("辰", "未") and 本气干 in ("戊", "己"):
            return 48.0
        return 原值 * 0.7
    if 型 == "截脚":
        return 原值 * (0.8 if 得令 else 0.7)
    if 型 == "盖头":
        return 原值 * (0.6 if 得令 else 0.5)
    return float(原值)


def 打分(四柱):
    """返回 dict：天干分、地支分、总分、档位、逐步过程。"""
    过程 = []
    日干, 日支 = 四柱[2][0], 四柱[2][1]
    日五行 = 五行[日干]

    # ---------- 天干 ----------
    型 = 柱型(日干, 日支)
    基准 = 天干特例.get((日干, 日支), 柱型基准[型])
    if 型 == "支生干" and 四柱[2] in 支生干_四十三:
        基准 = 43
    过程.append(f"日柱{四柱[2]}为{型}，天干基准{基准}分")

    增减 = 0
    for 位, 名 in ((1, "月干"), (3, "时干")):
        p = 天干增减(日干, 四柱[位][0])
        增减 += p
        过程.append(f"　{名}{四柱[位][0]}：{p:+d}%")
    年干 = 四柱[0][0]
    if 五行[年干] == 日五行:
        p = 20 if 阴阳[年干] == 阴阳[日干] else 30
        注 = ""
        if 五行[四柱[1][0]] != 日五行:
            p -= 10
            注 = "（月干非比劫，折让一成）"
        增减 += p
        过程.append(f"　年干{年干}为比劫：{p:+d}%{注}")
    天干分 = 基准 * (1 + 增减 / 100.0)
    过程.append(f"　天干合计 {基准}×{1 + 增减 / 100.0:.2f} = {天干分:.2f}")

    # ---------- 地支 ----------
    日支藏 = {五行[g] for g, _ in 藏干[日支]}
    日支有根 = 日五行 in 日支藏
    月支 = 四柱[1][1]
    月支有根 = any(五行[g] == 日五行 for g, _ in 藏干[月支])
    得令 = 日五行 in 月令旺相[月支]

    地支分 = 0.0
    for i in range(4):
        柱 = 四柱[i]
        gan, zhi = 柱[0], 柱[1]
        型2 = 柱型(gan, zhi)
        for 序, (hg, hv) in enumerate(藏干[zhi]):
            if 五行[hg] != 日五行:
                continue
            v = float(hv)
            if 序 == 0 and hv >= 60:            # 本气
                v = 本气分(柱, hg, hv, 型2, 得令)
                过程.append(f"　{柱}藏{hg}{hv}，{型2}{'得令' if 得令 else '失令'}→{v:.1f}")
            # 连根四档
            折 = 1.0
            if i == 0:                          # 年支
                if 月支有根:
                    折 = 1.0 if 日支有根 else 0.9
                else:
                    折 = 0.75
            elif i in (1, 3):                   # 月支、时支
                折 = 1.0 if 日支有根 else 0.9
            if 折 != 1.0:
                过程.append(f"　　不连根 ×{折} → {v * 折:.2f}")
            v *= 折
            地支分 += v

    # ---------- 合计 ----------
    总分 = 天干分 + 地支分
    return {"天干分": round(天干分, 2), "地支分": round(地支分, 2),
            "总分": round(总分, 2), "档位": 判定(总分), "过程": 过程}


def 判定(总分):
    for 限, 名 in 强弱档:
        if 总分 < 限:
            return 名
    return "专旺"


