def 释读(档名):
    d = 释义.get(档名)
    if not d:
        return []
    return [f"取用方向：{d['取用']}",
            f"断语力度：{d['力度']}",
            f"必做校核：{d['必做']}",
            f"健康倾向：{d['健康']}"]


# ---------------------------------------------------------------- 自检
def 自检():
    """判档唯一依据自己的体检。

    为什么必须补：本脚本是 `judging_basis=score-py` 的唯一实现，全馆旺衰判档都走它。
    它没有自检的那些年，「档位全错」和「档位全对」表现得一模一样——
    下面测的不是「能不能跑」，是**几条不许破的规矩**：值域、符号、边界不串档、总分恒等。
    """
    通过, 失败 = [], []

    def 查(名, 条件):
        (通过 if 条件 else 失败).append(名)

    # 一、柱型：五类认得准
    查("柱型·通根（甲寅）", 柱型("甲", "寅") == "通根")
    查("柱型·支生干（甲子，水生木）", 柱型("甲", "子") == "支生干")
    查("柱型·干生支（甲午，木生火）", 柱型("甲", "午") == "干生支")
    查("柱型·盖头（甲辰，木克土）", 柱型("甲", "辰") == "盖头")
    查("柱型·截脚（甲申，金克木）", 柱型("甲", "申") == "截脚")

    全域 = [柱型(g, z) for g in GAN for z in ZHI]
    查("柱型·全域不出五类之外", set(全域) <= {"通根", "支生干", "干生支", "盖头", "截脚"})
    查("柱型·「无关」分支不可达（五行两两非生即克）", "无关" not in 全域)

    # 二、天干增减：符号不许错，值域不许破
    查("增减·同我同阴阳 +20", 天干增减("甲", "甲") == 20)
    查("增减·同我异阴阳 +30", 天干增减("甲", "乙") == 30)
    查("增减·生我同阴阳 +20", 天干增减("甲", "壬") == 20)
    查("增减·生我异阴阳 +30", 天干增减("甲", "癸") == 30)
    查("增减·我生同阴阳 -20", 天干增减("甲", "丙") == -20)
    查("增减·我生异阴阳 -30", 天干增减("甲", "丁") == -30)
    查("增减·我克同阴阳 -30", 天干增减("甲", "戊") == -30)
    查("增减·我克异阴阳 -15", 天干增减("甲", "己") == -15)
    查("增减·克我同阴阳 -50", 天干增减("甲", "庚") == -50)
    查("增减·克我异阴阳 -30", 天干增减("甲", "辛") == -30)

    增减表 = {(g, h): 天干增减(g, h) for g in GAN for h in GAN}
    查("增减·值域不越 -50..30", all(-50 <= v <= 30 for v in 增减表.values()))
    查("增减·克我必为负",
       all(增减表[(g, h)] < 0 for g in GAN for h in GAN if 克[五行[h]] == 五行[g] and 五行[g] != 五行[h]))
    查("增减·同我必为正",
       all(增减表[(g, h)] > 0 for g in GAN for h in GAN if 五行[g] == 五行[h]))

    # 三、判定：阈值两侧不串档
    查("判定·0 分落最弱档", 判定(0) == "太弱")
    查("判定·44.99 仍太弱", 判定(44.99) == "太弱")
    查("判定·45 进偏弱", 判定(45) == "偏弱")
    查("判定·105 进中和", 判定(105) == "中和")
    查("判定·115 进偏旺", 判定(115) == "偏旺")
    查("判定·272 进太旺", 判定(272) == "太旺")
    查("判定·435 进专旺", 判定(435) == "专旺")
    序列 = [判定(x) for x in (0, 45, 105, 115, 272, 435)]
    查("判定·六档顺序不乱", 序列 == ["太弱", "偏弱", "中和", "偏旺", "太旺", "专旺"])
    查("判定·单调不减",
       all(序列.index(判定(a)) <= 序列.index(判定(b))
           for a in range(0, 500, 7) for b in (a + 7,)))

    # 四、表本身的自洽
    查("五行·十干齐备", set(五行) == set(GAN))
    查("支五行·十二支齐备", set(支五行) == set(ZHI))
    查("阴阳·十干各半", sum(1 for g in GAN if 阴阳[g] == "阳") == 5)
    查("藏干·十二支齐备", set(藏干) == set(ZHI))
    查("藏干·各支分值合计为百分", all(sum(v for _, v in 藏干[z]) == 100 for z in ZHI))
    查("藏干·本气居首且最高",
       all(藏干[z][0][1] == max(v for _, v in 藏干[z]) for z in ZHI))
    查("月令旺相·十二支齐备", set(月令旺相) == set(ZHI))

    # 用《打分方法》原话的五条规则反推每月该有哪些五行得令，再与表逐支比。
    # 为什么这样测：原先只测「当令者必在其中」，那条对「少收了几个」毫无办法——
    # 金在辰未丑缺失，正是这样漏掉的。
    季节 = {"春": "寅卯辰", "夏": "巳午未", "秋": "申酉戌", "冬": "亥子丑"}
    土月 = "辰戌丑未"
    得令支 = {
        "木": 季节["冬"] + 季节["春"],          # 木旺于冬春
        "火": 季节["春"] + 季节["夏"],          # 火旺于春夏
        "土": 季节["夏"] + 土月,                # 土旺于夏与四季土月
        "金": 季节["秋"] + 土月,                # 金旺于秋与四季土月
        "水": 季节["秋"] + 季节["冬"],          # 水旺于秋冬
    }
    期望 = {z: {h for h, 支们 in 得令支.items() if z in 支们} for z in ZHI}
    差 = {z: (期望[z], 月令旺相[z]) for z in ZHI if 期望[z] != 月令旺相[z]}
    查("月令旺相·按五条规则反推逐支相符（金在辰未丑也得令）", 差 == {})
    if 差:
        print("    不符：", {k: (sorted(a), sorted(b)) for k, (a, b) in list(差.items())[:4]})

    查("得令·金日主辰月得令（丙申柱不再按失令少算）",
       "金" in 月令旺相["辰"] and "金" in 月令旺相["未"] and "金" in 月令旺相["丑"])
    查("得令·金日主子月不得令", "金" not in 月令旺相["子"])
    查("得令·木日主亥月得令", "木" in 月令旺相["亥"])
    查("月令旺相·当令者必在其中",
       all(支五行[z] in 月令旺相[z] for z in ZHI))

    # 五、打分：总分恒等、可重复、过程有据
    盘 = ["壬子", "辛亥", "丙辰", "丁酉"]
    r = 打分(盘)
    查("打分·总分＝天干＋地支",
       abs(r["总分"] - round(r["天干分"] + r["地支分"], 2)) < 0.02)
    查("打分·两次结果一致", 打分(盘) == r)
    查("打分·档位在六档之内",
       r["档位"] in {"太弱", "偏弱", "中和", "偏旺", "太旺", "专旺"})
    查("打分·过程非空且有天干合计",
       bool(r["过程"]) and any("天干合计" in x for x in r["过程"]))
    查("打分·分数不为负", r["总分"] > 0)

    另一盘 = ["甲子", "丙寅", "甲寅", "乙亥"]
