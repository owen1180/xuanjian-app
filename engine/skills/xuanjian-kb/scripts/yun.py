# -*- coding: utf-8 -*-
"""岁运作用引擎：判大运流年与原局地支的合出、合入、合去、合走、冲、刑、害、空亡。

体例来源：四柱理学第三十二课「原局大运对应关系」、第四十三课「空亡」。
用法：
    python3 yun.py 丁酉 己酉 丙午 辛卯 --yun 乙未
    python3 yun.py 丁酉 己酉 丙午 辛卯 --yun 乙未 --liu 丙午
"""

GAN = "甲乙丙丁戊己庚辛壬癸"
ZHI = "子丑寅卯辰巳午未申酉戌亥"

五行 = {"甲": "木", "乙": "木", "丙": "火", "丁": "火", "戊": "土",
        "己": "土", "庚": "金", "辛": "金", "壬": "水", "癸": "水"}
支五行 = {"子": "水", "丑": "土", "寅": "木", "卯": "木", "辰": "土", "巳": "火",
          "午": "火", "未": "土", "申": "金", "酉": "金", "戌": "土", "亥": "水"}

生 = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
克 = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}

六合 = ["子丑", "寅亥", "卯戌", "辰酉", "巳申", "午未"]
三合 = {"水": "申子辰", "木": "亥卯未", "火": "寅午戌", "金": "巳酉丑"}
三会 = {"木": "寅卯辰", "火": "巳午未", "金": "申酉戌", "水": "亥子丑"}
六冲 = ["子午", "丑未", "寅申", "卯酉", "辰戌", "巳亥"]
六害 = ["子未", "丑午", "寅巳", "卯辰", "申亥", "酉戌"]
三刑 = {"寅巳申": "无恩之刑", "丑戌未": "恃势之刑", "子卯": "无礼之刑"}
自刑 = ["辰", "午", "酉", "亥"]

旬空表 = {"甲子": "戌亥", "甲戌": "申酉", "甲申": "午未",
          "甲午": "辰巳", "甲辰": "寅卯", "甲寅": "子丑"}


def 甲子序(干支):
    g, z = GAN.index(干支[0]), ZHI.index(干支[1])
    for i in range(60):
        if i % 10 == g and i % 12 == z:
            return i
    return -1


def 旬空(干支):
    序 = 甲子序(干支)
    首 = GAN[0] + ZHI[(序 - 序 % 10) % 12]
    return 旬空表.get(首, "")


def 关系(甲, 乙):
    """返回 (名称, 甲乙之间的生克走向)。"""
    if 甲 == 乙:
        return "伏吟", ""
    对 = 甲 + 乙
    if 对 in 六合 or 对[::-1] in 六合:
        a, b = 支五行[甲], 支五行[乙]
        if 生[a] == b:
            return "六合", f"{a}生{b}（生合）"
        if 克[a] == b:
            return "六合", f"{a}克{b}（克合）"
        return "六合", f"{b}生{a}（生合）"
    if 对 in 六冲 or 对[::-1] in 六冲:
        return "六冲", f"{支五行[甲]}与{支五行[乙]}相冲"
    if 对 in 六害 or 对[::-1] in 六害:
        return "六害", f"{支五行[甲]}与{支五行[乙]}相害"
    for 局, 名 in 三刑.items():
        if 甲 in 局 and 乙 in 局:
            return "三刑", f"同属{名}"
    if 甲 == 乙 and 甲 in 自刑:
        return "自刑", "同支自刑"
    return "", ""


def 半合(甲, 乙):
    for 行, 组 in 三合.items():
        if 甲 in 组 and 乙 in 组 and 甲 != 乙:
            a, b = 支五行[甲], 支五行[乙]
            if 生[a] == b:
                return "半三合", f"{a}生{b}（生合）", 行, True
            if 克[a] == b:
                return "半三合", f"{a}克{b}（克合）", 行, False
            return "半三合", f"{b}生{a}（生合）", 行, True
    return "", "", "", False


def 判岁运(原局, 运支, 名):
    """原局四支对一位岁运地支，逐支定性。"""
    出 = []
    局字 = [p[1] for p in 原局]
    for i, 位 in enumerate(("年支", "月支", "日支", "时支")):
        a = 局字[i]
        if a == 运支:
            注 = "，又为自刑，内耗自扰、反复折腾" if a in 自刑 else ""
            出.append(f"{位}{a}与{名}{运支}伏吟：旧事重来，同气叠加，该宫所主之事翻上台面{注}")
            continue
        称, 走向 = 关系(a, 运支)
        if 称 == "六合":
            if "生合" in 走向:
                if 生[支五行[a]] == 支五行[运支]:
                    出.append(f"{位}{a}合{名}{运支}：{走向}，原局{a}生岁运，力量被抽出，作「合出」，"
                             f"此支十年使不上劲，呈真空期；若为用神，则该宫所主之事悬空")
                else:
                    出.append(f"{位}{a}合{名}{运支}：{走向}，岁运生原局{a}，作「合入」，"
                             f"此支得助；为用神则吉，为忌神则仇神合入而生忌")
            else:
                if 克[支五行[a]] == 支五行[运支]:
                    出.append(f"{位}{a}合{名}{运支}：{走向}，原局克岁君，作「合走」，"
                             f"主动冲撞而受损最重，且反化为{支五行[运支]}，此支几乎失效")
                else:
                    出.append(f"{位}{a}合{名}{运支}：{走向}，岁君克原局，作「合去」，"
                             f"此支被制住；为用神则凶，为忌神则吉")
            continue
        称2, 走向2, 局, 顺 = 半合(a, 运支)
        if 称2:
            if 顺:
                出.append(f"{位}{a}与{名}{运支}{称2}：{走向2}，岁运为生方作「合入」，此支得助")
            elif 克[支五行[a]] == 支五行[运支]:
                出.append(f"{位}{a}与{名}{运支}{称2}：{走向2}，原局克岁君作「合走」，此支受损最重")
            else:
                出.append(f"{位}{a}与{名}{运支}{称2}：{走向2}，岁君克原局作「合去」，此支被制")
            continue
        if 称 == "六冲":
            出.append(f"{位}{a}冲{名}{运支}：原局永为被冲方，此支受制最烈；"
                     f"为用神则应凶，为忌神则应吉")
        elif 称 == "六害":
            出.append(f"{位}{a}害{名}{运支}：暗损，多应在人际与身体，不显于明面")
        elif 称 == "三刑":
            出.append(f"{位}{a}与{名}{运支}成刑：{走向}，刑入刑出看喜忌，生刑可刑出富贵，克刑则生是非")
        elif 称 == "自刑":
            出.append(f"{位}{a}与{名}{运支}自刑：内耗自扰，同一件事反复折腾")
    return 出


def 成局(原局, 运支):
    """三合、三会成局判定。"""
    局字 = [p[1] for p in 原局]
    出 = []
    for 行, 组 in 三合.items():
        if 运支 in 组:
            余 = [z for z in 组 if z != 运支]
            if all(z in 局字 for z in 余):
                v = 支五行[运支]
                if v == 行 or 生[v] == 行:
                    出.append(f"{行}局成：原局{'、'.join(余)}得{运支}，三合齐全，且{运支}生助{行}，成局有力")
                elif 生[行] == v:
                    出.append(f"{行}局不成：{运支}泄{行}之气，虽三字齐全而力散")
                elif 克[v] == 行:
                    出.append(f"{行}局不成：{运支}克{行}，三字虽齐而被制")
                else:
                    出.append(f"{行}局不成：{行}克{运支}，{运支}不受，难以成局")
    for 行, 组 in 三会.items():
        if 运支 in 组:
            余 = [z for z in 组 if z != 运支]
            if all(z in 局字 for z in 余):
                if 运支 in "辰戌丑未":
                    if 运支 == "戌" and 行 == "金":
                        出.append("金会成：戌为秋令，顺生金气，虽为土库仍可三会")
                    else:
                        出.append(f"{行}会不成：{运支}为土库，{('克' if 克[支五行[运支]] == 行 else '泄')}{行}，三会不成立")
                else:
                    出.append(f"{行}会成：原局{'、'.join(余)}得{运支}，三会成方，气势专一")
    return 出


def 查空(原局, 运干支):
    出 = []
    for 基准, 名 in ((原局[2], "日柱"), (原局[0], "年柱")):
        空 = 旬空(基准)
        if not 空:
            continue
        中 = [p[1] for p in 原局 if p[1] in 空]
        if 中:
            出.append(f"以{名}{基准}查，旬空在{空}；原局{'、'.join(中)}落空亡，力量大减，"
                     f"为用则好事减半，为忌则坏事减半")
    if 运干支:
        空日 = 旬空(原局[2])
        if 运干支[1] in 空日:
            出.append(f"{运干支}之支正填日柱空亡：空者填实，此支力量恢复，前所减半者到此复出")
        空年 = 旬空(原局[0])
        if 运干支[1] in 空年 and 运干支[1] not in 空日:
            出.append(f"{运干支}之支填年柱空亡：仅填一年之空，过此仍空")
    return 出


def 主(原局, 运干支="", 流干支=""):
    print("【原局】" + "　".join(原局))
    日空 = 旬空(原局[2])
    print(f"【空亡】日柱{原局[2]}属{日空}旬，空亡在{日空 or '无'}")
    for 干, 名 in ((运干支, "大运"), (流干支, "流年")):
        if not 干:
            continue
        print(f"\n【{名}{干}】")
        for l in 判岁运(原局, 干[1], 名):
            print("· " + l)
        for l in 成局(原局, 干[1]):
            print("· " + l)
        for l in 查空(原局, 干):
            print("· " + l)
    print("\n【次序】论吉凶先看大运，论力量流年重于大运；原局不能反过来影响岁运。")
    print("【分寸】合出、合去、冲入只说该支所主之事受阻或翻动，不断死、不断离、不断破财数额。")


# ---------------------------------------------------------------- 自检
def 自检():
    """岁运引擎自己的体检。

    为什么必须测：`regress.py` 的「考点」全靠本脚本输出的**行首位置标签**
    （`判岁运` 每行形如「月支→合入：…」，regress 用 split("：")[0] 抽位）。
    这条格式契约没人写下来过——哪天有人把分隔符改掉，回归器不会报错，
    只会安静地「什么都没抽到」，然后一切照旧绿灯。
    """
    通过, 失败 = [], []

    def 查(名, 条件):
        (通过 if 条件 else 失败).append(名)

    # 一、六十甲子序
    查("甲子序·甲子为 0", 甲子序("甲子") == 0)
    查("甲子序·乙丑为 1", 甲子序("乙丑") == 1)
    查("甲子序·甲戌为 10", 甲子序("甲戌") == 10)
    查("甲子序·丙午为 42", 甲子序("丙午") == 42)
    查("甲子序·癸亥为 59", 甲子序("癸亥") == 59)
    查("甲子序·非法组合给 -1（甲丑不存在）", 甲子序("甲丑") == -1)
    查("甲子序·六十组全可定位",
       all(甲子序(GAN[i % 10] + ZHI[i % 12]) == i for i in range(60)))

    # 二、旬空：六旬各一例，且空亡不在本旬内
    查("旬空·甲子旬空戌亥", 旬空("甲子") == "戌亥")
    查("旬空·甲戌旬空申酉", 旬空("甲戌") == "申酉")
    查("旬空·甲申旬空午未", 旬空("甲申") == "午未")
    查("旬空·甲午旬空辰巳", 旬空("甲午") == "辰巳")
    查("旬空·甲辰旬空寅卯", 旬空("甲辰") == "寅卯")
    查("旬空·甲寅旬空子丑", 旬空("甲寅") == "子丑")
    查("旬空·丙午日属甲辰旬", 旬空("丙午") == "寅卯")
    查("旬空·每旬都查得到", all(旬空(GAN[i] + ZHI[i % 12]) for i in range(10)))

    # 三、刑冲合害：已知组合
    查("关系·子丑六合", 关系("子", "丑")[0] == "六合")
    查("关系·子午六冲", 关系("子", "午")[0] == "六冲")
    查("关系·子未六害", 关系("子", "未")[0] == "六害")
    查("关系·丑戌三刑（无冲无害可判刑）", 关系("丑", "戌")[0] == "三刑")
    查("关系·子卯无礼之刑", 关系("子", "卯")[1].startswith("同属"))
    查("关系·寅巳判害不判刑（害先于刑，属现状未定案，见 TR111）",
       关系("寅", "巳")[0] == "六害")
    查("关系·同支判伏吟", 关系("午", "午")[0] == "伏吟")
    查("关系·自刑分支当前不可达（伏吟先行）",
       关系("辰", "辰")[0] == "伏吟" and 关系("酉", "酉")[0] == "伏吟")
    查("关系·六合必异支且成对", all(六合[i][0] != 六合[i][1] for i in range(len(六合))))
    查("关系·六冲支序恰差六",
       all((ZHI.index(y[1]) - ZHI.index(y[0])) % 12 == 6 for y in 六冲))
    查("关系·无关组合给空", 关系("子", "寅") == ("", ""))

    # 四、半合
    名, 走, 行, 生克 = 半合("寅", "午")
    查("半合·寅午成火局且为生合", 名 == "半三合" and 行 == "火" and 生克)
    名, _, 行, 生克 = 半合("巳", "酉")
    查("半合·巳酉成金局且为克合", 名 == "半三合" and 行 == "金" and not 生克)
    查("半合·同支不成半合（子子）", 半合("子", "子")[0] == "")
    查("半合·三合局每组三支齐", all(len(v) == 3 for v in 三合.values()))

    # 五、格式契约：regress 靠「行首位置＋全角冒号」抽考点
    原局 = ["丁酉", "己酉", "丙午", "辛卯"]
    判 = 判岁运(原局, "未", "大运") + 成局(原局, "未") + 查空(原局, "乙未")
    查("判岁运·返回列表", isinstance(判, list))
    查("判岁运·每行都带全角冒号（回归器靠它抽位置）",
       all("：" in x for x in 判岁运(原局, "未", "大运")) if 判岁运(原局, "未", "大运") else True)
    查("判岁运·有内容可抽", len(判) > 0)
    空 = 查空(原局, "乙未")
    查("查空·空亡能报出", bool(空) and any("空亡" in x for x in 空))
    查("查空·当前不带位置标签（格式债，改它要同步回归器与 TR111）",
       not any("：" in x for x in 空))

    print("通过 %d ／ 失败 %d" % (len(通过), len(失败)))
    for x in 失败:
        print("  ✗", x)
    return 0 if not 失败 else 1


if __name__ == "__main__":
    import sys as _sys
    if "--selftest" in _sys.argv:
        _sys.exit(自检())
    import sys
    args = sys.argv[1:]
    柱, 运, 流 = [], "", ""
    i = 0
    while i < len(args):
        if args[i] == "--yun":
            运 = args[i + 1]; i += 2
        elif args[i] == "--liu":
            流 = args[i + 1]; i += 2
        else:
            柱.append(args[i]); i += 1
    if len(柱) < 4:
        柱 = ["丁酉", "己酉", "丙午", "辛卯"]
    主(柱[:4], 运, 流)
