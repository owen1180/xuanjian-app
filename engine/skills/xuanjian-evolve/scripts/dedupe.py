#!/usr/bin/env python3
"""去重辅助 —— 批量语料入库前，先把「同一份东西」认出来。

用法：
    python3 dedupe.py 盘查 <采集目录> [--前 N] [--类 命理课程,倪海厦电子文案]
    python3 dedupe.py 出单 <采集目录> [--类 ...] [--out 保留清单.json]
    python3 dedupe.py --selftest

**为什么要有这个脚本**：外接盘采进 1,297 份，同名文件 116 组、涉及 388 份。
同一份《第47课 实践总结》在五个班级目录里各一份，内容一模一样。若不先去重：
提炼要在重复件上白做五遍；提案表里同一句话出现五次，人要裁五遍；
更坏的是「重复」会被误当成「多来源印证」——本馆立新概念要求「≥2 个独立来源」，
重复副本一旦混进去，这条规矩当场失效。

**两个键，各管一件事**：
- **内容**（首段哈希）管「这份是不是同一文」——它是去重的**主键**；
- **书名**（归一后）管「这个题目有没有出现多个不同内容」——它是**报警器**，不是主键。

单看任一个都会错：
- 只看书名：`讲义(1)` 与 `讲义` 确实是同一份，但 `命理按分数分类-105-115分`
  在两个班里可能是不同人整理的两版，得看内容才能定。
- 只看内容：整本转载与节选转载首段相同、正文不同，前者能合并、后者不能。

**四型**：

| 型 | 判据 | 处置 |
|---|---|---|
| `dup` | 首段相同 + 同名 | 留一份，其余记别名 |
| `rename` | 首段相同 + 异名 | 留一份，其余记别名（重命名副本） |
| `same_name_diff` | 同名 + 内容不同 | **全留**，单列待看 |
| `unique` | 内容独一无二 | 全留 |

**「高度相似」只报不并——这条是踩出来的。** 起初加过一型 `near_dup`：
同名、正文四元组重叠 ≥0.90、字数差 ≤25%，就合并。第一版跑真数据就误合了两份——
`倪醫師病案紀錄 (229)` 与 `(230)` 重叠 0.948、字数差 10%：它们是**同一病人同日两诊**，
230 那张方多出白芍五钱、丹皮三钱、补骨脂三钱、泽泻五钱、黄柏——
**并掉就等于丢一张方**。而病案这一类恰恰全是同一个模板开头，重叠天然很高。

所以改成：**能证明是同一份的（首段哈希相同）才合并；只是像的，列进 `近文` 名单让人看。**
判据要能承受到「错的代价是永久丢内容」，就不能用相似度。

顺带一提，`打分方法` 那两份（1,075 字 / 1,211 字）差别其实是排版：
一版用 `- ` 列表、一版是自动编号 `1 .`，另有自动生成的「分支主题 6」噪声行。
这个靠**加强归一**（剥行首列表标记与半角标点）解决，不靠相似度。

**三条纪律**（写死，不许改）：
1. **不删源文件**。只出「保留清单 + 别名表」，删不删由人定；采集目录是只读产物。
2. **同名异文不合并**。可能是一本书的两版、一节课的两稿，合并等于丢内容；
   宁可让 300 组挂在那儿让人看一眼，也不许自动选一份当代表。
3. **只认账里 `ok` 的**。采集账里 `thin`（近空·疑扫描）与 `skipped` 的产物
   不许进来——盘上有 33 个这样的 `.md`，正文只有页码或广告，混进来会污染哈希。
"""
import hashlib
import json
import os
import re
import sys

首段取字 = 200      # 首段哈希取前多少字（归一后）
最少段长 = 40       # 累加到这么长的归一正文，才够当「开头」
最短行 = 12         # 短于此的行（标题、页码）跳过，不参与首段

# 副本痕迹：只去纯数字与常见副本词，不去有意义的中文括注
# （`（第4次）` 是课次，`（2021年）` 是年份，都不能当副本标记剥掉）
_副本尾 = re.compile(r"(?:\s*[-_－]?\s*副本|\((\d+)\)|（(\d+)）|\s+copy\d*)$", re.I)
_多余空白 = re.compile(r"\s+")
# 行首列表标记：`- `／`* `／`1. `／`1 . `／`一、`。转出来的一份常带自动编号，
# 另一份没有——不剥掉，同文不同排版就会被当成两份（`打分方法` 实测踩过）。
_列表头 = re.compile(r"^[ \t]*(?:[-*•·]+|\d+[ \t]*[.、．)]|[一二三四五六七八九十]+[、.．)])[ \t]*", re.M)
_半角标点 = re.compile(r"[.,;:!?'\"()\[\]{}<>]")
# 行尾自动编号：思维导图导出常见「甲辰柱，甲木 36 分不变 1 .」——
# 编号被粘在正文行末，剥不掉的话同一份文档两种导出方式会算出 0.82 的相似度。
_尾部编号 = re.compile(r"[ \t]+\d+[ \t]*\.[ \t]*$", re.M)


def 归一(s):
    """归一：去空白、去常见标点。中文语料里空格与标点差异最会骗过比对。"""
    s = s or ""
    s = re.sub(r"[，。、；：！？「」『』（）()《》〈〉“”‘’…—\-\[\]【】]", "", s)
    return _多余空白.sub("", s)


def 归一比(s):
    """**比对专用**归一：在 `归一` 之上再剥行首列表标记与半角标点。

    为什么不直接改 `归一`：`归一` 还要用来数字数，剥掉编号会让字数虚低；
    书名也不该剥列表标记。比对只求「同一文」，不必求「同一个字」。
    """
    s = _尾部编号.sub("", s or "")
    s = _列表头.sub("", s)
    return 归一(_半角标点.sub("", s))


def 书名(路径):
    """书名：去扩展名、去副本痕迹、归一小写。"""
    b = os.path.basename(路径 or "")
    b = os.path.splitext(b)[0]
    b = _副本尾.sub("", b)
    return 归一(b).lower()


def 正文(路):
    """读采集产物里「---头---」之后的正文。头里有源路径与字符数，不能算进哈希。"""
    try:
        t = open(路, encoding="utf-8", errors="replace").read()
    except OSError:
        return ""
    if t.startswith("---"):
        k = t.find("\n---", 3)
        if k > 0:
            t = t[k + 4:]
    return t


def 首段(文):
    """拼够长的「开头」：跳过标题行与页码行，累到 `最少段长` 为止。

    为什么要累而不是取第一段：课堂笔记一份常只有几百字，段落都是二三十字，
    取第一段不够长、容易撞；直接退化成「全文哈希」又太严，删一行注释就不认了。
    跳过 <12 字的行，是因为标题行、页码行在各版本里都一样——拿它们比，
    会让《第47课》与《第47课（修订）》看起来「同文」。
    """
    累 = []
    for 段 in re.split(r"\n\s*\n|\n", 文 or ""):
        段 = 段.strip()
        if len(归一(段)) < 最短行:
            continue
        累.append(段)
        if len(归一("\n".join(累))) >= 最少段长:
            break
    return "\n".join(累) if 累 else (文 or "").strip()


def 首段哈希(文, 取=首段取字):
    return hashlib.sha1(归一比(首段(文))[:取].encode("utf-8")).hexdigest()[:12]


def 四元集(文):
    """归一正文的四元组集合，用来算「同文不同排版」的近似度。

    用字符四元组而不是 SequenceMatcher：后者在 346 个同名病案上是 O(n²) 的
    逐字符比对，慢到跑不完；集合求交是线性的，且对「换行、列表符号、
    自动编号」这类排版差异天然不敏感。
    """
    s = 归一比(文)
    if len(s) < 4:
        return {s} if s else set()
    return {s[i:i + 4] for i in range(len(s) - 3)}


def 近似度(甲, 乙):
    """重叠系数（交集 ÷ 较小集合）。0～1，1 表示小的那份被大的完全包含。

    为什么不用 Jaccard：Jaccard 的分母是并集，只要一边多一句前言，
    自己就把分数压到 0.8 以下——而「多一句前言」恰恰是最常见的同文变体。
    用重叠系数会带来另一个风险：**节选本会被判成 1.0**。所以本函数不单独承担
    判重责任，`分型` 里另有「字数差不得超 25%」的前置闸——节选本过不了那道闸。
    """
    if not 甲 or not 乙:
        return 0.0
    return len(甲 & 乙) / min(len(甲), len(乙))


def 排序选一(同们):
    """留谁：字数最多 → 路径最短（层级最浅）→ 路径字典序。

    为什么不随机留一份：同一份东西在不同目录里字数可能不同（有的带目录、
    有的带批注），留字多的那份信息损失最小；字数相同则留层级浅的，好找。
    """
    return sorted(同们, key=lambda x: (-x.get("字", 0), len(x["路"]), x["路"]))[0]


def 分型(条目们, 近似阈=0.90, 字数容差=0.25):
    """按内容聚，再按名字标。返回 (组们, 同名异文名单)。

    三步：
    1. **精确聚**：同一个首段哈希归一组，组内留一份、其余记别名；
       名字相同记 `dup`、名字不同记 `rename`——后者说明有人给它改过名。
    2. **近似并**：同一个名字下、内容不同的几份，若正文四元组重叠系数 ≥ 阈值
       且字数差在容差内，判 `near_dup` 合并（排版不同，不是两版）。
       字数差超容差一律不并——那是「节选本 vs 全本」，并了就是丢内容。
    3. **同名异文**：并完之后，一个名字下仍有多个内容的，才列进待人工看的名单。
    """
    按文 = {}
    for x in 条目们:
        按文.setdefault(x["杂凑"], []).append(x)

    组们 = []
    for 杂, 同们 in 按文.items():
        保留 = 排序选一(同们)
        别名们 = [x for x in 同们 if x is not 保留]
        if not 别名们:
            型, 理由 = "unique", "内容独一无二"
        else:
            名们 = {x["名"] for x in 同们}
            if len(名们) == 1:
                型 = "dup"
                理由 = "同名且首段相同（%d 份）" % len(同们)
            else:
                型 = "rename"
                理由 = "首段相同但名字有 %d 种（%d 份），疑重命名副本" % (len(名们), len(同们))
        组们.append({"型": 型, "杂凑": 杂, "名": 保留["名"],
                   "保留": 保留, "别名们": 别名们, "理由": 理由})

    # ── 近文：同名之下高度相似，**只报不并** ──────────────────────────
    按名 = {}
    for g in 组们:
        按名.setdefault(g["名"], []).append(g)

    近文 = []
    for 名, 同组 in 按名.items():
        if len(同组) < 2:
            continue
        for a in range(len(同组)):
            for b in range(a + 1, len(同组)):
                xa, xb = 同组[a]["保留"], 同组[b]["保留"]
                if not xa.get("集") or not xb.get("集"):
                    continue
                长们 = sorted((xa.get("字", 0), xb.get("字", 0)))
                if 长们[0] == 0 or (长们[1] - 长们[0]) / max(长们[1], 1) > 字数容差:
                    continue          # 字数差太多：多半是节选本，连提示都不必
                近 = 近似度(xa["集"], xb["集"])
                if 近 < 近似阈:
                    continue
                近文.append({"名": 名, "近似": round(近, 3),
                           "甲": xa["路"], "乙": xb["路"],
                           "甲字": xa.get("字", 0), "乙字": xb.get("字", 0),
                           "提示": "疑同文不同排版或同案两诊，须人看，未合并"})
    近文.sort(key=lambda g: -g["近似"])

    # ── 同名异文：同一名字下有多个内容，全留待看 ───────────────────────
    同名异文 = []
    for 名, 同组 in 按名.items():
        内容数 = len(同组)
        份数 = sum(1 + len(g["别名们"]) for g in 同组)
        if 内容数 > 1:
            同名异文.append({"名": 名, "份数": 份数, "内容数": 内容数,
                           "路们": [g["保留"]["路"] for g in 同组]})
    同名异文.sort(key=lambda g: (-g["内容数"], g["名"]))
    return 组们, 同名异文, 近文


def 扫(根, 前=0, 类们=None):
    """扫采集目录。**有账就按账来**：只收状态 `ok` 且产物真在盘上的。

    为什么必须按账：盘上有 33 个 `.md` 是 `thin`（196 页扫描本只抽到 69 个页码字）
    或广告页（「♨️免费精品资源仓」）。它们躺在目录里，光看扩展名分不出来，
    混进哈希会把「近空」当成一份独立语料，还会跟真册子撞名。
    """
    账路 = os.path.join(根, "_index.json")
    出 = []
    if os.path.exists(账路):
        for x in json.load(open(账路, encoding="utf-8")).get("entries", []):
            if x.get("status") != "ok" or not x.get("out"):
                continue
            if 类们 and not any(k in x["out"] for k in 类们):
                continue
            路 = os.path.join(根, x["out"])
            if not os.path.exists(路):
                continue
            文 = 正文(路)
            出.append({"路": 路, "名": 书名(路), "杂凑": 首段哈希(文),
                       "字": len(归一(文)), "集": 四元集(文), "账": x})
            if 前 and len(出) >= 前:
                return 出
        return 出
    # 无账（比如只给一个子目录）时退回走目录
    for 目, _, 文件们 in os.walk(根):
        for f in sorted(文件们):
            if not f.endswith(".md") or f.startswith("_"):
                continue
            路 = os.path.join(目, f)
            if 类们 and not any(k in 路 for k in 类们):
                continue
            文 = 正文(路)
            出.append({"路": 路, "名": 书名(f), "杂凑": 首段哈希(文),
                       "字": len(归一(文)), "集": 四元集(文), "账": None})
            if 前 and len(出) >= 前:
                return 出
    return 出


def 盘查(根, 前=0, 类们=None):
    条 = 扫(根, 前, 类们)
    组们, 同名异文, 近文 = 分型(条)
    计 = {}
    for g in 组们:
        计[g["型"]] = 计.get(g["型"], 0) + 1
    省 = sum(len(g["别名们"]) for g in 组们)
    return {"总数": len(条), "组数": len(组们), "可省": 省, "分布": 计,
            "组": 组们, "同名异文": 同名异文, "近文": 近文}


def 出单(根, 前=0, 类们=None):
    """出保留清单。返回 {keep, alias, same_name_diff, stat}。"""
    r = 盘查(根, 前, 类们)
    keep, alias = [], {}
    for g in r["组"]:
        keep.append(g["保留"]["路"])
        for x in g["别名们"]:
            alias[x["路"]] = {"to": g["保留"]["路"], "型": g["型"], "理由": g["理由"]}
    return {"keep": sorted(keep), "alias": alias,
            "same_name_diff": r["同名异文"], "near": r["近文"],
            "stat": {"总数": r["总数"], "保留": len(keep), "别名": len(alias),
                     "同名异文组": len(r["同名异文"]), "近文对": len(r["近文"]),
                     "分布": r["分布"]}}


# ---------------------------------------------------------------- 自检
def 自检():
    """去重器自己的体检。

    为什么必须测它：去重是**减法**，错一次就是永久丢内容，而且丢得毫无痕迹——
    保留清单照样能跑、提炼照样出提案，只是少了一半料，没有任何一处会报错。
    所以这里专测四件：
    ① 归一真的把标点空格差异吃掉；② 副本标记只剥数字型、不剥有意义的括注；
    ③ 四型判对（尤其「同名异文」一份都不许合）；④ 账里的 thin 不进扫描。
    """
    通过, 失败 = [], []

    def 查(名, 条件):
        (通过 if 条件 else 失败).append(名)

    # ── 一、归一 ────────────────────────────────────────────────────────
    查("归一·去空格", 归一("天 干 五 合") == 归一("天干五合"))
    查("归一·去中文标点", 归一("同性相克，主克方减力。") == 归一("同性相克主克方减力"))
    查("归一·去英文括号", 归一("分数(105)") == 归一("分数105"))
    查("归一·空值不炸", 归一(None) == "" and 归一("") == "")

    # ── 二、书名 ────────────────────────────────────────────────────────
    查("书名·去扩展名", 书名("第47课 实践总结.docx") == 归一("第47课 实践总结"))
    查("书名·去 (1) 副本标记", 书名("讲义(1).docx") == 书名("讲义.docx"))
    查("书名·去全角（2）", 书名("讲义（2）.docx") == 书名("讲义.docx"))
    查("书名·去「副本」", 书名("讲义 - 副本.docx") == 书名("讲义.docx"))
    查("书名·保留课次括注（（第4次）不是副本）",
       书名("第47课 实践总结（第4次）.docx") != 书名("第47课 实践总结.docx"))
    查("书名·保留年份括注", 书名("作业（2021年）.docx") != 书名("作业.docx"))
    查("书名·大小写不敏感", 书名("ABC.md") == 书名("abc.md"))

    # ── 三、首段与哈希 ──────────────────────────────────────────────────
    长文甲 = "# 标题\n\n这是第一段正文，讲同性相克与异性相克的不同减力比例。\n\n第二段。"
    长文乙 = "# 换了个标题\n\n这是第一段正文，讲同性相克与异性相克的不同减力比例。\n\n第二段不同。"
    查("首段·跳过标题行", 首段(长文甲).startswith("这是第一段正文"))
    查("首段·标题不同不影响哈希", 首段哈希(长文甲) == 首段哈希(长文乙))
    查("首段·短于 12 字的行不参与",
       首段("短标题\n\n这是一段足够长的正文，用来验证短行不会被当成首段拿来算哈希值。")
       .startswith("这是一段足够长"))
    查("哈希·标点差异不改变", 首段哈希("甲，乙。丙" * 20) == 首段哈希("甲乙丙" * 20))
    查("哈希·不同内容不同值", 首段哈希("完全不同的内容" * 20) != 首段哈希("另一些内容" * 20))
    查("哈希·定长 12", len(首段哈希("任意" * 100)) == 12)

    # ── 四、四型判定 ────────────────────────────────────────────────────
    def 条(名_, 杂_, 字_=100, 路_=None):
        return {"路": 路_ or ("/x/%s-%s-%d.md" % (名_, 杂_, 字_)), "名": 名_,
                "杂凑": 杂_, "字": 字_}

    份 = [条("甲", "h1", 100), 条("甲", "h1", 200), 条("乙", "h2"),
          条("丙", "h3"), 条("丁", "h3", 300)]
    组们, 同名异文, 近文0 = 分型(份)
